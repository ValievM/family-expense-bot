package telegram

// Command — пункт меню бота рядом с полем ввода.
type Command struct {
	Name        string
	Description string
}

// Profile — то, что видит человек до первого сообщения: описание над кнопкой запуска и меню команд.
type Profile struct {
	Description      string
	ShortDescription string
	Commands         []Command
}

